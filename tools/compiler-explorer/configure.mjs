import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const upstream = path.join(here, '.work/upstream');

async function insert(file, anchor, addition, marker) {
    const target = path.join(upstream, file);
    const text = await fs.readFile(target, 'utf8');
    if (text.includes(marker)) return;
    if (!text.includes(anchor)) throw new Error(`Upstream registration point changed: ${file}`);
    await fs.writeFile(target, text.replace(anchor, anchor + addition));
}

